"""One-click trace -> pinned pytest regression test.

Turns a recorded run into a deterministic test: replays the run with
every step served from the recording, then asserts the final output
matches the pinned trace. No vendor account, no network, runs in CI.
"""

HEADER = """# Pinned regression test generated by Forkwise.
# Run ID: {run_id}  Pipeline: {run_name}
# Every step is served from the recorded trace, so this test is
# deterministic and needs no network or vendor account. To re-execute
# steps live from a fork point instead, pass that step number as
# from_seq to replay_run (the pipeline module must be importable).
"""

BODY = """
from forkwise.replay import replay_run
from forkwise.sdk import Tracer

PINNED_RUN_ID = {run_id!r}
EXPECTED_OUTPUT_JSON = {expected_output!r}
STEP_COUNT = {step_count}

# TODO: import the module that defines your pipeline so it registers
# with the tracer, and point DB_PATH at a copy of the trace database.
DB_PATH = "forkwise.db"


def test_pinned_trace_reproduces():
    tracer = Tracer(DB_PATH)
    new_run, diff = replay_run(
        tracer, PINNED_RUN_ID, from_seq=STEP_COUNT + 1)
    assert diff["output_changed"] is False
    assert new_run["output_json"] == EXPECTED_OUTPUT_JSON
"""


def generate_test(store, run_id):
    run = store.get_run(run_id)
    if run is None:
        raise ValueError("no such run: %s" % run_id)
    spans = store.get_spans(run_id)
    header = HEADER.format(run_id=run_id, run_name=run["name"])
    body = BODY.format(run_id=run_id, expected_output=run["output_json"],
                       step_count=len(spans))
    return header + body
